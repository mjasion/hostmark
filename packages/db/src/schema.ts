import { sql } from 'drizzle-orm';
import {
  bigint,
  boolean,
  date,
  index,
  integer,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uuid,
} from 'drizzle-orm/pg-core';

const timestamptz = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

// Better Auth tables. Property names are what its Drizzle adapter looks up; keep them in step with
// the Better Auth version in packages/core.

export const user = pgTable('user', {
  id: text('id').primaryKey(),
  name: text('name').notNull(),
  email: text('email').notNull().unique(),
  emailVerified: boolean('email_verified').notNull().default(false),
  image: text('image'),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
  updatedAt: timestamptz('updated_at').notNull().defaultNow(),
});

export const session = pgTable(
  'session',
  {
    id: text('id').primaryKey(),
    expiresAt: timestamptz('expires_at').notNull(),
    token: text('token').notNull().unique(),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    updatedAt: timestamptz('updated_at').notNull().defaultNow(),
    ipAddress: text('ip_address'),
    userAgent: text('user_agent'),
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
  },
  (t) => [index('session_user_id').on(t.userId)],
);

export const account = pgTable(
  'account',
  {
    id: text('id').primaryKey(),
    accountId: text('account_id').notNull(),
    providerId: text('provider_id').notNull(),
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    accessToken: text('access_token'),
    refreshToken: text('refresh_token'),
    idToken: text('id_token'),
    accessTokenExpiresAt: timestamptz('access_token_expires_at'),
    refreshTokenExpiresAt: timestamptz('refresh_token_expires_at'),
    scope: text('scope'),
    password: text('password'),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    updatedAt: timestamptz('updated_at').notNull().defaultNow(),
  },
  (t) => [index('account_user_id').on(t.userId)],
);

export const verification = pgTable(
  'verification',
  {
    id: text('id').primaryKey(),
    identifier: text('identifier').notNull(),
    value: text('value').notNull(),
    expiresAt: timestamptz('expires_at').notNull(),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    updatedAt: timestamptz('updated_at').notNull().defaultNow(),
  },
  (t) => [index('verification_identifier').on(t.identifier)],
);

// Application tables (spec "Database schema", D7, D13)

export const fileStatus = pgEnum('file_status', [
  'pending_upload',
  'queued',
  'processing',
  'ready',
  'failed',
  'deleted',
]);

export const apiKeys = pgTable('api_keys', {
  id: uuid('id').primaryKey().defaultRandom(),
  userId: text('user_id')
    .notNull()
    .references(() => user.id),
  keyHash: text('key_hash').notNull().unique(), // sha256 hex
  name: text('name').notNull(),
  isAdmin: boolean('is_admin').notNull().default(false),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
});

export const files = pgTable(
  'files',
  {
    id: uuid('id').primaryKey(), // uuidv7, generated by the application
    userId: text('user_id')
      .notNull()
      .references(() => user.id),
    apiKeyId: uuid('api_key_id').references(() => apiKeys.id, { onDelete: 'set null' }), // null for uploads from the panel
    status: fileStatus('status').notNull().default('pending_upload'),
    contentType: text('content_type').notNull(),
    bytes: integer('bytes'),
    width: integer('width'),
    height: integer('height'),
    sha256: text('sha256'),
    originalKey: text('original_key').notNull(),
    isPublic: boolean('is_public').notNull().default(false),
    attempts: integer('attempts').notNull().default(0),
    lastError: text('last_error'),
    expiresAt: timestamptz('expires_at').notNull(),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    queuedAt: timestamptz('queued_at'),
    lastActivityAt: timestamptz('last_activity_at').notNull().defaultNow(),
    readyAt: timestamptz('ready_at'),
    deletedAt: timestamptz('deleted_at'),
    purgedAt: timestamptz('purged_at'),
  },
  (t) => [
    index('files_user_created').on(t.userId, t.id.desc().nullsFirst()).where(sql`${t.deletedAt} is null`),
    index('files_expires').on(t.expiresAt).where(sql`${t.deletedAt} is null`),
    index('files_sha').on(t.sha256),
    // requeue-stuck (D19)
    index('files_activity').on(t.lastActivityAt).where(sql`${t.status} in ('queued', 'processing')`),
    // cleanup-expired: rows whose objects still need purging (D19)
    index('files_unpurged').on(t.id).where(sql`${t.status} = 'deleted' and ${t.purgedAt} is null`),
  ],
);

export const fileVariants = pgTable(
  'file_variants',
  {
    fileId: uuid('file_id')
      .notNull()
      .references(() => files.id, { onDelete: 'cascade' }),
    size: integer('size').notNull(), // longer side in px: 128, 512, 1600
    storageKey: text('storage_key').notNull(),
    bytes: integer('bytes').notNull(),
  },
  (t) => [primaryKey({ columns: [t.fileId, t.size] })],
);

export const dailyStats = pgTable(
  'daily_stats',
  {
    day: date('day', { mode: 'string' }).notNull(),
    platform: text('platform').notNull(),
    uploads: integer('uploads').notNull(),
    ready: integer('ready').notNull(),
    failed: integer('failed').notNull(),
    bytesIn: bigint('bytes_in', { mode: 'number' }).notNull(),
    p50ProcessingMs: integer('p50_processing_ms'),
    p95ProcessingMs: integer('p95_processing_ms'),
  },
  (t) => [primaryKey({ columns: [t.day, t.platform] })],
);
