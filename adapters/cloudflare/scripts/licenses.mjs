// Writes licenses/THIRD-PARTY-LICENSES.txt: the licence text of every package that ends up in a Worker bundle, plus the
// codec licences of the WebAssembly modules, which carry no comments of their own. A deployed bundle has no
// node_modules, so the texts travel inside it (src/licenses.ts imports the file; the api serves it).
//   node scripts/licenses.mjs          writes the file
//   node scripts/licenses.mjs --check  fails when the file is out of date
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'licenses', 'THIRD-PARTY-LICENSES.txt');
const entries = ['api', 'consumer', 'scheduler'].map((n) => join(root, 'src', `${n}.ts`));

const packages = new Map();
function packageDirOf(file) {
  const m = file.match(/^(.*\/node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  return m?.[1];
}

for (const entry of entries) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    metafile: true,
    format: 'esm',
    // Only the set of packages matters here, not the output; wrangler does the real bundling.
    platform: 'node',
    conditions: ['workerd', 'worker', 'browser', 'import'],
    external: ['cloudflare:*'],
    loader: { '.wasm': 'empty', '.txt': 'empty' },
    logLevel: 'error',
  });
  for (const input of Object.keys(result.metafile.inputs)) {
    const dir = packageDirOf(resolve(root, input));
    if (dir) packages.set(dir, true);
  }
}

function licenseFiles(dir) {
  return readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying|notice)/i.test(f))
    .sort()
    .map((f) => join(dir, f));
}

const sections = [];
for (const dir of [...packages.keys()].sort()) {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const files = licenseFiles(dir);
  const header = `${pkg.name}@${pkg.version} (${typeof pkg.license === 'string' ? pkg.license : JSON.stringify(pkg.license ?? 'see package')})`;
  sections.push(
    [
      header,
      ...files.map((f) => readFileSync(f, 'utf8').trim()),
      ...(files.length ? [] : ['(the package ships no licence file)']),
    ].join('\n\n'),
  );
}

// The codecs: the wasm files come from these packages and are covered by the licences next to them.
const codecs = [];
for (const name of ['jpeg', 'png', 'webp', 'resize']) {
  const dir = join(root, 'node_modules', '@jsquash', name);
  for (const rel of ['codec/LICENSE.codec.md', 'LICENSE']) {
    const f = join(dir, rel);
    if (existsSync(f)) codecs.push(`@jsquash/${name}: ${rel}\n\n${readFileSync(f, 'utf8').trim()}`);
  }
}

const text = `${[
  'Third-party licences of the hostmark Cloudflare adapter bundles. Generated by scripts/licenses.mjs; do not edit.',
  '## Codecs (WebAssembly modules)',
  ...codecs,
  '## Packages bundled into the Workers',
  ...sections,
].join('\n\n----------------------------------------\n\n')}\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== text) {
    console.error('licenses/THIRD-PARTY-LICENSES.txt is out of date: run `pnpm licenses`');
    process.exit(1);
  }
  console.log(`licences up to date (${packages.size} packages)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${packages.size} packages, ${text.length} bytes`);
}
